def _ts(t: float | None) -> str:
    return time.strftime("%Y-%m-%d %H:%M", time.localtime(t)) if t else ""


def _user() -> User | None:
    try:
        return security.user_from_token(ng_app.storage.user.get("token"))
    except security.AuthError:
        ng_app.storage.user.pop("token", None)
        return None


def _guard(admin: bool = False) -> User | None:
    user = _user()
    if not user:
        ui.navigate.to("/login")
        return None
    if admin and not user.is_admin:
        ui.label("403 - admin role required").classes("text-negative text-h6 q-pa-lg")
        return None
    _header(user)
    return user


def _notify_error(exc: Exception) -> None:
    ui.notify(str(exc) or exc.__class__.__name__, type="negative", multi_line=True)


def _header(user: User) -> None:
    with ui.header().classes("items-center justify-between bg-primary"):
        with ui.row().classes("items-center gap-4"):
            ui.label("Document Knowledge Assistant").classes("text-h6")
            for label, path in [("Chat", "/"), ("Documents", "/documents"), ("Memory & history", "/memory"),
                                ("Account", "/account")] + ([("Admin", "/admin")] if user.is_admin else []):
                ui.link(label, path).classes("text-white no-underline")
        with ui.row().classes("items-center"):
            ui.label(f"{user.username} ({user.role})")

            def logout():
                security.logout(ng_app.storage.user.pop("token", None))
                ui.navigate.to("/login")
            ui.button("Logout", on_click=logout, icon="logout").props("flat color=white")


