def _documents_table(user: User, docs: list[dict], refreshable) -> None:
    cols = [{"name": k, "label": l, "field": k, "align": "left"} for k, l in
            [("filename", "File"), ("file_type", "Type"), ("visibility", "Visibility"), ("owner", "Owner"),
             ("status", "Status"), ("n_chunks", "Chunks"), ("error", "Error"), ("created", "Uploaded"), ("actions", "")]]
    rows = [dict(d, created=_ts(d["created_at"]), can_delete=user.is_admin or d["owner_id"] == user.id) for d in docs]
    t = ui.table(columns=cols, rows=rows, row_key="id").classes("w-full").props("data-testid=documents-table")
    t.add_slot("body-cell-status", '<q-td :props="props"><q-badge :color="{ready:\'positive\',processing:\'warning\',queued:\'info\',error:\'negative\'}[props.value]" :label="props.value" /></q-td>')
    t.add_slot("body-cell-actions", '<q-td :props="props"><q-btn v-if="props.row.can_delete" flat dense icon="delete" color="negative" @click="$parent.$emit(\'delete\', props.row)" /></q-td>')

    def delete(e):
        try:
            indexing.delete_document(user, e.args["id"], current())
            ui.notify("Deleted (removed from retrieval index)")
        except Exception as exc:
            _notify_error(exc)
        refreshable.refresh()
    t.on("delete", delete)


