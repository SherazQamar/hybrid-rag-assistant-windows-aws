def _admin_profiles(admin: User) -> None:
    state = {"profile": profiles.active()}
    inputs: dict[tuple[str, str], ui.element] = {}

    @ui.refreshable
    def header():
        active = profiles.active()["name"]
        ui.label(f"Active profile: {active}").classes("text-h6")
        if indexing.reindex_needed():
            ui.label("Active profile's chunking/embedding differs from the live index -> run a reindex "
                     "(Index versions tab). Until then the old index keeps serving.").classes("text-warning")

    header()
    with ui.row().classes("items-center"):
        picker = ui.select([p["name"] for p in profiles.list_all()], value=state["profile"]["name"], label="Profile").classes("w-64")
        name = ui.input("Name", value=state["profile"]["name"])
        desc = ui.input("Description", value=state["profile"].get("description", "")).classes("w-96")

    with ui.grid(columns=4).classes("w-full"):
        for sec, key, label, kind, opts in FIELDS:
            val = state["profile"][sec][key]
            if kind == "select":
                inputs[(sec, key)] = ui.select(opts, value=val, label=label)
            elif kind == "multi":
                inputs[(sec, key)] = ui.select(opts, value=val, label=label, multiple=True)
            elif kind == "text":
                inputs[(sec, key)] = ui.input(label, value=val)
            else:
                inputs[(sec, key)] = ui.number(label, value=val, step=0.05 if kind == "float" else 1)

    def load(p: dict):
        state["profile"] = p
        name.value, desc.value = p["name"], p.get("description", "")
        for (sec, key), el in inputs.items():
            el.value = p[sec][key]

    picker.on_value_change(lambda e: load(profiles.get(e.value)) if e.value else None)

    def collect() -> dict:
        p = {"name": name.value, "description": desc.value, "chunking": {}, "embedding": {}, "retrieval": {}, "context": {}}
        for (sec, key), el in inputs.items():
            kind = next(f[3] for f in FIELDS if f[0] == sec and f[1] == key)
            v = el.value
            p[sec][key] = int(v) if kind == "number" and v is not None else float(v) if kind == "float" and v is not None else v
        return p

    def refresh_picker():
        picker.set_options([p["name"] for p in profiles.list_all()], value=name.value)

    def save():
        try:
            profiles.save(collect())
            refresh_picker()
            ui.notify("Profile saved", type="positive")
        except Exception as exc:
            _notify_error(exc)

    def activate():
        try:
            profiles.activate(picker.value)
            header.refresh()
            ui.notify(f"Activated {picker.value}", type="positive")
        except Exception as exc:
            _notify_error(exc)

    def delete():
        try:
            profiles.delete(picker.value)
            refresh_picker()
            load(profiles.active())
        except Exception as exc:
            _notify_error(exc)

    async def do_import(e: events.UploadEventArguments):
        try:
            p = profiles.import_json(await e.file.text())
            refresh_picker()
            load(p)
            ui.notify(f"Imported {p['name']}", type="positive")
        except Exception as exc:
            _notify_error(exc)

    with ui.row().classes("items-center"):
        ui.button("Save", icon="save", on_click=save)
        ui.button("Activate selected", icon="check", on_click=activate)
        ui.button("Export JSON", icon="download",
                  on_click=lambda: ui.download.content(profiles.export_json(picker.value), f"{picker.value}.json"))
        ui.upload(label="Import JSON", on_upload=do_import, auto_upload=True).props('accept=".json"').classes("w-64")
        ui.button("Delete", icon="delete", color="negative", on_click=delete).props("outline")

    ui.separator()
    ui.label("Chunk preview (uses the form values above, does not change the live index)").classes("text-h6")
    docs = {d["id"]: d["filename"] for d in indexing.visible_documents(admin) if d["status"] == "ready"}
    with ui.row().classes("items-center"):
        doc_sel = ui.select(docs, label="Document").classes("w-72")
        preview_area = ui.column().classes("w-full")

    def preview():
        preview_area.clear()
        try:
            res = admin_tools.chunk_preview(doc_sel.value, collect(), current())
        except Exception as exc:
            _notify_error(exc)
            return
        with preview_area:
            ui.label(f"{res['document']}: {res['total_chunks']} chunks with {json.dumps(res['settings'])}")
            for c in res["chunks"]:
                with ui.card().classes("w-full"):
                    loc = f"page {c['page']}" if c["page"] else f"section {c['section']}" if c["section"] else ""
                    ui.label(f"#{c['ordinal']}  chars {c['start_char']}-{c['end_char']}  ({c['chars']} chars / "
                             f"{c['tokens']} tokens)  {loc}").classes("text-caption text-bold")
                    ui.label(c["text"]).style("white-space: pre-wrap").classes("text-caption")
    ui.button("Preview chunks", on_click=preview)


def _admin_index() -> None:
    @ui.refreshable
    def versions():
        v = indexing.active_version()
        if v:
            ui.label(f"Live index: version {v['id']} - profile '{v['profile_name']}', embedding "
                     f"{v['embed_provider']}/{v['embed_model']} ({v['embed_dim']}-d)").classes("text-bold")
        if indexing.reindex_needed():
            ui.label("Reindex required for the active profile's settings.").classes("text-warning")
        rows = [dict(r, created=_ts(r["created_at"]), activated=_ts(r["activated_at"]), pct=f"{r['progress'] * 100:.0f}%")
                for r in indexing.list_versions()]
        cols = [{"name": k, "label": l, "field": k, "align": "left"} for k, l in
                [("id", "Version"), ("profile_name", "Profile"), ("status", "Status"), ("pct", "Progress"),
                 ("n_chunks", "Chunks"), ("embed_model", "Embedding model"), ("embed_dim", "Dim"),
                 ("chunking_json", "Chunking"), ("error", "Error"), ("created", "Created"), ("activated", "Activated")]]
        ui.table(columns=cols, rows=rows, row_key="id").classes("w-full")

    def start(fail_after=None):
        try:
            indexing.start_reindex(current(), fail_after)
            ui.notify("Reindex started", type="info")
        except Exception as exc:
            _notify_error(exc)
        versions.refresh()

    with ui.row():
        ui.button("Reindex with active profile", icon="refresh", on_click=lambda: start())
        ui.button("Demo: simulate failed rebuild", icon="error", on_click=lambda: start(1)).props("outline color=negative")
    versions()
    ui.timer(2.0, versions.refresh)


