@ui.page("/login")
def login_page():
    if _user():
        ui.navigate.to("/")
        return

    def try_login():
        try:
            token = security.login(username.value, password.value, totp.value or None, current())
        except Exception as exc:  # generic message, no detail on which factor failed
            _notify_error(exc)
            return
        ng_app.storage.user["token"] = token
        ui.navigate.to("/")

    with ui.card().classes("absolute-center w-96"):
        ui.label("Sign in").classes("text-h5")
        username = ui.input("Username").props("autofocus").classes("w-full")
        password = ui.input("Password", password=True, password_toggle_button=True).classes("w-full")
        totp = ui.input("MFA code (if enabled)").classes("w-full")
        password.on("keydown.enter", try_login)
        totp.on("keydown.enter", try_login)
        ui.button("Login", on_click=try_login).classes("w-full").props("data-testid=login")


