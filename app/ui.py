        ui.label(f"Manual key: {secret}").classes("text-caption")
        code = ui.input("Code")

        def enable():
            try:
                security.enable_mfa(user.id, secret, code.value)
                ui.notify("MFA enabled", type="positive")
                ui.navigate.reload()
            except Exception as exc:
                _notify_error(exc)
        ui.button("Enable MFA", on_click=enable)


