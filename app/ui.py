@ui.page("/")
def chat_page():
    user = _guard()
    if not user:
        return
    store = ng_app.storage.user
    prof = profiles.active()

    def select(chat_id: int | None):
        store["chat_id"] = chat_id
        chat_list.refresh()
        conversation.refresh()

    def new_chat():
        select(agent.create_chat(user))

    with ui.left_drawer(value=True).classes("bg-grey-2"):
        ui.button("New chat", icon="add", on_click=new_chat).classes("w-full").props("data-testid=new-chat")

        @ui.refreshable
        def chat_list():
            for c in agent.list_chats(user):
                active = c["id"] == store.get("chat_id")
                with ui.row().classes("w-full items-center no-wrap" + (" bg-blue-1" if active else "")):
                    ui.button(c["title"][:32], on_click=lambda c=c: select(c["id"])).props("flat dense no-caps align=left").classes("grow")

                    def remove(c=c):
                        agent.delete_chat(user, c["id"])
                        select(None if store.get("chat_id") == c["id"] else store.get("chat_id"))
                    ui.button(icon="delete", on_click=remove).props("flat dense round size=sm")
        chat_list()

    @ui.refreshable
    def conversation():
        chat_id = store.get("chat_id")
        if not chat_id:
            ui.label("Start a new chat or pick one on the left.").classes("text-grey q-pa-md")
            return
        try:
            msgs = agent.messages(user, chat_id)
        except LookupError:
            store["chat_id"] = None
            return
        for m in msgs:
            _message(m["role"], m["content"], m["sources"])
        pending = [m for m in memory.list_for(user) if m["status"] == "pending"]
        for p in pending:
            with ui.card().classes("bg-amber-1 w-full"):
                ui.label("Approve this note for long-term memory?").classes("text-bold")
                ui.label(p["content"])
                with ui.row():
                    ui.button("Approve", on_click=lambda p=p: (memory.approve(user, p["id"]), conversation.refresh())).props("color=positive data-testid=approve-memory")
                    ui.button("Reject", on_click=lambda p=p: (memory.delete(user, p["id"]), conversation.refresh())).props("color=negative flat")

    with ui.column().classes("w-full max-w-4xl mx-auto"):
        conversation()
        with ui.row().classes("w-full items-end no-wrap"):
            mode = ui.select(list(profiles.MODES), value=prof["retrieval"]["default_mode"], label="Retrieval").classes("w-32")
            question = ui.textarea(placeholder="Ask about your documents, or 'Remember that ...'").props("autogrow outlined data-testid=question").classes("grow")
            spinner = ui.spinner(size="lg")
            spinner.visible = False

            async def send():
                text = (question.value or "").strip()
                if not text:
                    return
                if not store.get("chat_id"):
                    store["chat_id"] = agent.create_chat(user)
                question.value, spinner.visible = "", True
                try:
                    await run.io_bound(agent.ask, user, store["chat_id"], text, mode.value, current())
                except Exception as exc:
                    _notify_error(exc)
                finally:
                    spinner.visible = False
                chat_list.refresh()
                conversation.refresh()
            ui.button(icon="send", on_click=send).props("round data-testid=send")
            question.on("keydown.ctrl.enter", send)


def _message(role: str, content: str, sources: list) -> None:
    mine = role == "user"
    with ui.card().classes(("bg-blue-1 self-end" if mine else "bg-white") + " max-w-3xl").props(f"data-testid={role}-message"):
        ui.label(content).style("white-space: pre-wrap")  # label = escaped text, never HTML
        if sources:
            with ui.expansion(f"Sources ({len(sources)})", icon="menu_book").classes("w-full text-caption"):
                for s in sources:
                    ui.label(f"[{s['n']}] {s['ref']}  - score {s['score']}").classes("text-bold").props("data-testid=source-ref")
                    ui.label(s["snippet"]).classes("text-grey-8").style("white-space: pre-wrap")


